// Builds the app into self-contained HTML files.
//   dist/signal-box-simulator.html  – one file: double-click to run on a PC, or copy to a phone
//   dist/claude-hosted/artifact.html – the same page without the outer <html> skeleton, for publishing to the
//                                  hosted copy on claude.ai (not for opening directly)
//   dist/pwa/                    – installable web app (needs to be served over https, e.g. GitHub Pages)
//
// Run with either:  bun scripts/build.mjs      or      node scripts/build.mjs  (needs: npm i -D esbuild)
import { mkdirSync, readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...x) => join(root, ...x);

// 1. Embed the bell recording as a data URL module.
const bell = readFileSync(p('assets', 'bell-trimmed.mp3')).toString('base64');
writeFileSync(
  p('src', 'audio', 'bellData.generated.ts'),
  `// Generated by scripts/build.mjs from assets/bell-trimmed.mp3. Do not edit.\nexport const DEFAULT_BELL = 'data:audio/mpeg;base64,${bell}';\n`,
);

// 2. Bundle the TypeScript.
let js;
if (typeof Bun !== 'undefined') {
  const out = await Bun.build({ entrypoints: [p('src', 'main.ts')], minify: true, target: 'browser', format: 'iife' });
  if (!out.success) {
    console.error(out.logs);
    process.exit(1);
  }
  js = await out.outputs[0].text();
} else {
  const esbuild = await import('esbuild');
  const out = await esbuild.build({ entryPoints: [p('src', 'main.ts')], bundle: true, minify: true, format: 'iife', write: false, target: 'es2020' });
  js = out.outputFiles[0].text;
}
js = js.replace(/<\/script/gi, '<\\/script');
const css = readFileSync(p('src', 'styles.css'), 'utf8');

const fonts =
  '<link rel="preconnect" href="https://fonts.googleapis.com">\n' +
  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n' +
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Abril+Fatface&family=Alfa+Slab+One&family=Barlow+Condensed:wght@500;600;700&family=IBM+Plex+Mono:wght@400;600&family=Josefin+Sans:wght@600;700&family=Old+Standard+TT:ital,wght@0,400;0,700;1,400&family=Source+Sans+3:wght@400;600;700&family=Special+Elite&display=swap">';
const title = '<title>Signal Box Simulator</title>';
const body = `<div id="app"></div>\n<script>${js}</script>`;

mkdirSync(p('dist', 'pwa'), { recursive: true });
mkdirSync(p('dist', 'claude-hosted'), { recursive: true });
const template = readFileSync(p('index.html'), 'utf8');

// Single file
writeFileSync(
  p('dist', 'signal-box-simulator.html'),
  template.replace('<!--HEAD-->', `${title}\n<meta name="theme-color" content="#1f5546">\n${fonts}\n<style>${css}</style>`).replace('<!--BODY-->', body),
);

// Artifact page (the host adds the doctype/head/body skeleton)
writeFileSync(
  p('dist', 'claude-hosted', 'artifact.html'),
  `${title}\n<meta name="claude:viewport-fit-sides" content="cover">\n${fonts}\n<style>${css}</style>\n${body}\n`,
);

// PWA
writeFileSync(
  p('dist', 'pwa', 'index.html'),
  template
    .replace('<!--HEAD-->', `${title}\n<meta name="theme-color" content="#1f5546">\n<link rel="manifest" href="manifest.webmanifest">\n<link rel="icon" href="icon.svg">\n${fonts}\n<style>${css}</style>`)
    .replace('<!--BODY-->', body),
);
for (const f of ['manifest.webmanifest', 'sw.js', 'icon.svg', 'icon-192.png', 'icon-512.png']) {
  if (existsSync(p('public', f))) copyFileSync(p('public', f), p('dist', 'pwa', f));
}
console.log(`Built: ${(js.length / 1024).toFixed(0)} KB script`);
